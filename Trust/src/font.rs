const GLYPH_W: u32 = 5;
const GLYPH_H: u32 = 7;
const GLYPH_GAP: u32 = 1;

fn glyph_for(byte: u8) -> &'static [u8; 7] {
    if (0x20..=0x7E).contains(&byte) {
        &FONT_5X7[(byte - 0x20) as usize]
    } else {
        &FONT_5X7[0] // blank
    }
}

fn unpack_rgba(argb_or_rgba: u32) -> [u8; 4] {
    // Matches the u32 the caller already packs as 0xRRGGBBAA-style (as used
    // elsewhere in this codebase's `color_rgba` conventions): highest byte
    // red, down to lowest byte alpha.
    [
        ((argb_or_rgba >> 24) & 0xFF) as u8,
        ((argb_or_rgba >> 16) & 0xFF) as u8,
        ((argb_or_rgba >> 8) & 0xFF) as u8,
        (argb_or_rgba & 0xFF) as u8,
    ]
}

/// Renders `text` as a single-line bitmap into `out_rgba`, `scale`x scaled,
/// glyph pixels tinted `fg_rgba`, background pixels `bg_rgba` (0 = fully
/// transparent). Returns the number of bytes written (0 on failure), and
/// writes the actual pixel width/height to `out_w`/`out_h`.
pub fn render_text(
    text: &str,
    scale: u32,
    fg_rgba: u32,
    bg_rgba: u32,
    out_rgba: &mut [u8],
    out_w: &mut u32,
    out_h: &mut u32,
) -> usize {
    let scale = scale.max(1);
    let chars: Vec<u8> = text.bytes().collect();
    if chars.is_empty() {
        *out_w = 0;
        *out_h = 0;
        return 0;
    }

    let cell_w = (GLYPH_W + GLYPH_GAP) * scale;
    let width = cell_w * chars.len() as u32;
    let height = GLYPH_H * scale;
    let needed = (width * height * 4) as usize;
    if needed == 0 || out_rgba.len() < needed {
        *out_w = 0;
        *out_h = 0;
        return 0;
    }

    let fg = unpack_rgba(fg_rgba);
    let bg = unpack_rgba(bg_rgba);

    for row in out_rgba[..needed].chunks_exact_mut(4) {
        row.copy_from_slice(&bg);
    }

    for (ci, &b) in chars.iter().enumerate() {
        let glyph = glyph_for(b);
        let x0 = ci as u32 * cell_w;
        for gy in 0..GLYPH_H {
            let bits = glyph[gy as usize];
            for gx in 0..GLYPH_W {
                // bit 4 = leftmost column, bit 0 = rightmost.
                let on = (bits >> (GLYPH_W - 1 - gx)) & 1 != 0;
                if !on {
                    continue;
                }
                for sy in 0..scale {
                    let py = gy * scale + sy;
                    for sx in 0..scale {
                        let px = x0 + gx * scale + sx;
                        let idx = ((py * width + px) * 4) as usize;
                        if idx + 4 <= needed {
                            out_rgba[idx..idx + 4].copy_from_slice(&fg);
                        }
                    }
                }
            }
        }
    }

    *out_w = width;
    *out_h = height;
    needed
}

/// Renders `text` with an energized neon glow aura around glyphs.
/// Glyph core is tinted `core_rgba`, and the outer blur halo is tinted `glow_rgba`.
pub fn render_text_electric(
    text: &str,
    scale: u32,
    core_rgba: u32,
    glow_rgba: u32,
    glow_radius: u32,
    out_rgba: &mut [u8],
    out_w: &mut u32,
    out_h: &mut u32,
) -> usize {
    let scale = scale.max(1);
    let chars: Vec<u8> = text.bytes().collect();
    if chars.is_empty() {
        *out_w = 0;
        *out_h = 0;
        return 0;
    }

    let pad = glow_radius.clamp(1, 12);
    let cell_w = (GLYPH_W + GLYPH_GAP) * scale;
    let base_w = cell_w * chars.len() as u32;
    let base_h = GLYPH_H * scale;
    let width = base_w + pad * 2;
    let height = base_h + pad * 2;
    let needed = (width * height * 4) as usize;
    if needed == 0 || out_rgba.len() < needed {
        *out_w = 0;
        *out_h = 0;
        return 0;
    }

    // Zero-fill buffer
    out_rgba[..needed].fill(0);

    let [gr, gg, gb, ga] = unpack_rgba(glow_rgba);
    let [cr, cg, cb, ca] = unpack_rgba(core_rgba);
    let r_f = pad as f32;

    // Collect all core pixel locations
    let mut core_pixels = Vec::with_capacity(chars.len() * 35 * (scale * scale) as usize);
    for (ci, &b) in chars.iter().enumerate() {
        let glyph = glyph_for(b);
        let x0 = pad + ci as u32 * cell_w;
        for gy in 0..GLYPH_H {
            let bits = glyph[gy as usize];
            for gx in 0..GLYPH_W {
                let on = (bits >> (GLYPH_W - 1 - gx)) & 1 != 0;
                if !on {
                    continue;
                }
                for sy in 0..scale {
                    let py = pad + gy * scale + sy;
                    for sx in 0..scale {
                        let px = x0 + gx * scale + sx;
                        core_pixels.push((px, py));
                    }
                }
            }
        }
    }

    // Pass 1: Glow accumulation
    if ga > 0 {
        let pad_i = pad as i32;
        for &(cx, cy) in &core_pixels {
            let cx_i = cx as i32;
            let cy_i = cy as i32;
            for dy in -pad_i..=pad_i {
                let py = cy_i + dy;
                if py < 0 || py >= height as i32 {
                    continue;
                }
                for dx in -pad_i..=pad_i {
                    let px = cx_i + dx;
                    if px < 0 || px >= width as i32 {
                        continue;
                    }
                    let dist_sq = (dx * dx + dy * dy) as f32;
                    if dist_sq <= r_f * r_f {
                        let dist = dist_sq.sqrt();
                        let falloff = (1.0 - dist / (r_f + 0.5)).max(0.0).powf(1.4);
                        let idx = ((py as u32 * width + px as u32) * 4) as usize;
                        let a_add = (ga as f32 * falloff * 0.55) as u16;
                        let cur_a = out_rgba[idx + 3] as u16;
                        let new_a = (cur_a + a_add).min(255) as u8;
                        out_rgba[idx] = gr;
                        out_rgba[idx + 1] = gg;
                        out_rgba[idx + 2] = gb;
                        out_rgba[idx + 3] = new_a;
                    }
                }
            }
        }
    }

    // Pass 2: Sharp core pixels
    for &(cx, cy) in &core_pixels {
        let idx = ((cy * width + cx) * 4) as usize;
        out_rgba[idx] = cr;
        out_rgba[idx + 1] = cg;
        out_rgba[idx + 2] = cb;
        out_rgba[idx + 3] = ca;
    }

    *out_w = width;
    *out_h = height;
    needed
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_render_text_electric() {
        let mut buf = vec![0u8; 100 * 100 * 4];
        let mut w = 0;
        let mut h = 0;
        let bytes = render_text_electric(
            "Zap!",
            2,
            0xFFFFFFFF,
            0x00F0FFFF,
            3,
            &mut buf,
            &mut w,
            &mut h,
        );
        assert!(bytes > 0, "Electric text render should write bytes");
        assert!(w > 0 && h > 0, "Width and height must be positive");
    }
}

